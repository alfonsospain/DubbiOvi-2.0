import { resolveFFmpegExecutable } from '../main.js';
import { AudioMixdownService } from '../src/lib/AudioMixdownService';
import type { Take } from '../src/lib/types';
import { spawn } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';

async function runFFmpegRuntimeValidation() {
  console.log('=====================================================');
  console.log(' MILESTONE 15.4A - FFMPEG RUNTIME VALIDATION SUITE    ');
  console.log('=====================================================');

  // 1. Resolve Executable
  const resolvedPath = resolveFFmpegExecutable();
  console.log('\nResolved FFmpeg executable:\n' + resolvedPath);

  const expectedLocalPath = path.join(process.cwd(), 'bin', 'ffmpeg');
  if (resolvedPath !== expectedLocalPath) {
    console.error(`\n❌ Resolution mismatch! Expected: ${expectedLocalPath}, Got: ${resolvedPath}`);
    process.exit(1);
  }
  console.log('✓ resolveFFmpegExecutable() successfully resolved project-local binary first.');

  // 2. Prepare real test input audio files using FFmpeg
  const tempOutputDir = path.join(process.cwd(), 'tmp');
  if (!fs.existsSync(tempOutputDir)) {
    fs.mkdirSync(tempOutputDir, { recursive: true });
  }

  const inputVideoPath = path.join(tempOutputDir, 'input_original.wav');
  const takeVoicePath = path.join(tempOutputDir, 'take_voice_asset.wav');
  const outputWavPath = path.join(tempOutputDir, 'test_validation_output.wav');

  if (fs.existsSync(outputWavPath)) {
    fs.unlinkSync(outputWavPath);
  }

  console.log('\n[Creating synthetic test audio inputs...]');
  // Generate 3 sec 440Hz original track
  await new Promise<void>((resolve, reject) => {
    const p1 = spawn(resolvedPath, ['-y', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=3', inputVideoPath]);
    p1.on('close', (code) => (code === 0 ? resolve() : reject(new Error(`Failed to create inputOriginal: ${code}`))));
  });

  // Generate 1.5 sec 880Hz voice take track
  await new Promise<void>((resolve, reject) => {
    const p2 = spawn(resolvedPath, ['-y', '-f', 'lavfi', '-i', 'sine=frequency=880:duration=1.5', takeVoicePath]);
    p2.on('close', (code) => (code === 0 ? resolve() : reject(new Error(`Failed to create takeVoice: ${code}`))));
  });

  console.log('  ✓ Created test input original audio:', inputVideoPath);
  console.log('  ✓ Created test input voice take audio:', takeVoicePath);

  const sampleTakes: Take[] = [
    {
      id: 'take-val-1',
      character: 'Validator',
      time: '00:00.500 - 00:02.000',
      startSeconds: 0.5,
      endSeconds: 2.0,
      original: 'Validation test line',
      translation: 'Línea de prueba de validación',
      voiceAssetId: 'asset-1',
      notes: '',
      status: 'Reviewed',
    },
  ];

  const mockAssetManager = {
    getAsset: () => ({ relativePath: takeVoicePath }),
    getActiveAssetForTake: () => ({ relativePath: takeVoicePath }),
  } as any;

  // Build FFmpeg command using AudioMixdownService with real inputs
  const cmdResult = AudioMixdownService.buildFFmpegCommand(
    {
      videoFile: null,
      takes: sampleTakes,
      getAssetManager: () => mockAssetManager,
      originalVolume: 0.8,
      originalEnabled: true,
      voiceVolume: 1.0,
      voiceEnabled: true,
      outputFormat: 'wav',
    },
    inputVideoPath,
    outputWavPath
  );

  console.log('\n[FFmpeg Command Generated by AudioMixdownService]:');
  console.log('Args:', JSON.stringify(cmdResult.ffmpegArgs));
  console.log('Full Command:', cmdResult.fullCommand);

  // 3. Launch FFmpeg process directly using spawn()
  console.log('\n[Launching FFmpeg Process...]');
  let spawnSuccess = false;
  let exitCode: number | null = null;
  let stdout = '';
  let stderr = '';
  let spawnError = '';

  const startTime = Date.now();

  await new Promise<void>((resolve) => {
    try {
      const proc = spawn(resolvedPath, cmdResult.ffmpegArgs, { windowsHide: true });
      spawnSuccess = true;

      proc.stdout.on('data', (data) => {
        stdout += data.toString();
      });

      proc.stderr.on('data', (data) => {
        stderr += data.toString();
      });

      proc.on('error', (err) => {
        spawnError = err.message;
        console.error('Spawn error:', err);
        resolve();
      });

      proc.on('close', (code) => {
        exitCode = code;
        resolve();
      });
    } catch (err: any) {
      spawnError = err?.message || String(err);
      resolve();
    }
  });

  const durationMs = Date.now() - startTime;

  // 4. Inspect generated WAV file
  const fileExists = fs.existsSync(outputWavPath);
  const fileSize = fileExists ? fs.statSync(outputWavPath).size : 0;

  let isValidWav = false;
  if (fileExists && fileSize >= 44) {
    const buffer = Buffer.alloc(12);
    const fd = fs.openSync(outputWavPath, 'r');
    fs.readSync(fd, buffer, 0, 12, 0);
    fs.closeSync(fd);

    const riffHeader = buffer.toString('ascii', 0, 4);
    const waveFormat = buffer.toString('ascii', 8, 12);
    if (riffHeader === 'RIFF' && waveFormat === 'WAVE') {
      isValidWav = true;
    }
  }

  // 5. Output Final Validation Report
  console.log('\n=====================================================');
  console.log('              VALIDATION REPORT - 15.4A             ');
  console.log('=====================================================');
  console.log(`• Resolved FFmpeg Path: ${resolvedPath}`);
  console.log(`• Executed Command: ${resolvedPath} ${cmdResult.ffmpegArgs.join(' ')}`);
  console.log(`• Spawn Result: ${spawnSuccess ? `SUCCESS (PID active during ${durationMs}ms)` : `FAILED (${spawnError})`}`);
  console.log(`• Exit Code: ${exitCode}`);
  console.log(`• Stdout Length: ${stdout.length} bytes`);
  console.log(`• Stderr Snippet:\n${stderr.trim() || '(empty stderr)'}`);
  console.log(`• WAV Generated: ${fileExists ? `YES (${fileSize} bytes)` : 'NO'}`);
  console.log(`• WAV Validity: ${isValidWav ? 'VALID (RIFF/WAVE header verified)' : 'INVALID'}`);

  if (exitCode === 0 && isValidWav) {
    console.log('\n✅ MILESTONE 15.4A FFMPEG RUNTIME VALIDATION PASSED SUCCESSFULLY!');
  } else {
    console.error('\n❌ VALIDATION FAILED!');
    console.error(`Root Cause Analysis: exitCode=${exitCode}, spawnError=${spawnError}, isValidWav=${isValidWav}`);
    process.exit(1);
  }
}

runFFmpegRuntimeValidation().catch((err) => {
  console.error('\n❌ Unhandled Validation Exception:', err);
  process.exit(1);
});
